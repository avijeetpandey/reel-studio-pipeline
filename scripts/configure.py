#!/usr/bin/env python3
"""Write the Reel Studio config + channel rules and install the template into the studio folder.

  python3 -I configure.py --answers answers.json --plugin <plugin root>

answers.json keys (all strings unless noted): creator_name, brand, handle, yt_handle, role, promise, accent, avatar,
confidential, niche, audience, languages, prefer, avoid, series, length, cta, timezone, slots, music_rule,
gate_script (bool), gate_preview (bool), drive_remote, drive_folder (empty = no uploads), studio_dir, platforms.
Safe to re-run: existing reels/, carousels/, research/, style_log.md and music files are kept.
"""
import argparse, json, os, shutil

DEFAULTS = {
    "creator_name": "", "brand": "", "handle": "", "yt_handle": "", "role": "", "promise": "one useful idea every day",
    "accent": "#3ee0ff", "avatar": "", "confidential": "", "niche": "", "audience": "", "languages": "English",
    "prefer": "broad curiosity and career topics", "avoid": "", "series": "", "length": "25–35 s of speech, hard cap 40 s",
    "cta": "one debatable yes/no question; never 'comment KEYWORD for a DM'", "timezone": "Asia/Kolkata",
    "slots": "Instagram 7–9 PM, YouTube 12–2 PM; one reel per day; never two on one platform within 12 h; never 11 PM–9 AM",
    "music_rule": "YouTube Audio Library 'Attribution not required' only; the pipeline picks and downloads tracks without asking",
    "gate_script": True, "gate_preview": True, "drive_remote": "gdrive", "drive_folder": "reels",
    "studio_dir": "~/Documents/reel-studio", "platforms": "Instagram Reels, YouTube Shorts, LinkedIn post, carousel",
    "whisper_model": "~/.cache/hyperframes/whisper/models/ggml-small.en.bin",
}
TOKENS = {"__BRAND__": "brand", "__HANDLE__": "handle", "__NAME__": "creator_name", "__ROLE__": "role",
          "__PROMISE__": "promise", "__ACCENT__": "accent"}

RULES = """# Channel rules — {brand} (@{handle})
Generated by the studio-setup skill on first run. Every Reel Studio skill reads this file; it overrides default numbers in the skills.
Edit it by hand or re-run "studio setup".

## About me
- Name on screen: **{creator_name}** · role / credibility: **{role}**
- Niche: {niche}
- Audience: {audience} · spoken language(s): {languages}
- Follow-card promise: "{promise}" · accent colour {accent}
- Confidential (never reveal internals, never imply endorsement): {confidential}
- Series I run: {series}

## Content rules
- Length: {length}. One idea, one everyday analogy, one twist line.
- Open on the payoff: first line is a plain-English claim, no jargon in the first 2 s, my face visible from frame 1.
- CTA: {cta}. The last line loops into the first.
- Prefer: {prefer}. Avoid: {avoid}.
- Patterns learned from reference reels: `$STUDIO/template/WINNING_PATTERNS.md` (grows every time I run `study:`).

## Posting
- Timezone: {timezone}. Slots: {slots}.

## Music
- {music_rule}. Every reel gets music, energetic from the first second, mixed under the voice.

## Approval gates (never skip)
- Ask me whenever a sign-in is needed.
- Script + shoot sheet approval before filming (checkpoint 1): {gate_script}.
- Studio preview approval before the final render (checkpoint 2): {gate_preview}.
- Upload: {upload}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--answers", required=True)
    ap.add_argument("--plugin", required=True)
    a = ap.parse_args()
    cfg_path = os.path.expanduser("~/.config/reel-studio/config.json")
    old = json.load(open(cfg_path)) if os.path.exists(cfg_path) else {}
    ans = json.load(open(a.answers))
    cfg = {**DEFAULTS, **old, **{k: v for k, v in ans.items() if v not in (None, "")}}
    cfg["plugin_root"] = os.path.abspath(os.path.expanduser(a.plugin))
    studio = os.path.expanduser(cfg["studio_dir"])
    os.makedirs(os.path.dirname(cfg_path), exist_ok=True)
    json.dump(cfg, open(cfg_path, "w"), indent=2, ensure_ascii=False)

    for d in ("reels", "carousels", "research", "inbox", "broll"):
        os.makedirs(os.path.join(studio, d), exist_ok=True)
    # template: copy fresh files, fill tokens, never delete the user's media
    src = os.path.join(cfg["plugin_root"], "template"); dst = os.path.join(studio, "template")
    for root, _, files in os.walk(src):
        for f in files:
            s = os.path.join(root, f); d = os.path.join(dst, os.path.relpath(s, src))
            os.makedirs(os.path.dirname(d), exist_ok=True)
            try:
                t = open(s, encoding="utf-8").read()
                for tok, key in TOKENS.items():
                    t = t.replace(tok, str(cfg.get(key) or ""))
                open(d, "w", encoding="utf-8").write(t)
            except UnicodeDecodeError:
                shutil.copy2(s, d)
            if os.access(s, os.X_OK):
                os.chmod(d, 0o755)
    for sub in ("composition/assets/audio/music", "composition/assets/audio/sfx", "carousel/assets", "composition/assets/broll"):
        os.makedirs(os.path.join(dst, sub), exist_ok=True)
    if cfg.get("avatar") and os.path.exists(os.path.expanduser(cfg["avatar"])):
        shutil.copy2(os.path.expanduser(cfg["avatar"]), os.path.join(dst, "carousel/assets/avatar-cartoon.png"))
    idx = os.path.join(dst, "composition/assets/audio/music/INDEX.md")
    if not os.path.exists(idx):
        open(idx, "w").write("# Approved music library (YouTube Audio Library, \"Attribution not required\")\n"
                             "**How to pick:** `python3 -I $STUDIO/template/scripts/pick_music.py --len <s> --mood <mood>`; add tracks with "
                             "`music_energy.py` (energy ≥ 72). Rows: file | mood | bpm | notes (must contain `energy N/100` and `start at S s`).\n\n"
                             "| file | mood | bpm | notes |\n|---|---|---|---|\n")
    log = os.path.join(studio, "reels/style_log.md")
    if not os.path.exists(log):
        open(log, "w").write("# Style log — read before choosing a treatment, append after every render\n\n"
                             "| date | reel | treatment | signature move | scene mix | caption highlight | music |\n|---|---|---|---|---|---|---|\n\n"
                             "## Carousels\n\n| date | carousel | format | layouts (in order) | paired reel |\n|---|---|---|---|---|\n")
    upload = (f"to Google Drive `{cfg['drive_remote']}:{cfg['drive_folder']}/<reel_name>/` (always a NEW subfolder) only after I approve BOTH the video and the thumbnails"
              if cfg.get("drive_folder") else "no uploads — keep deliverables in the reel folder")
    open(os.path.join(studio, "CHANNEL_RULES.md"), "w").write(RULES.format(**{**cfg, "upload": upload}))
    print(f"config: {cfg_path}\nstudio: {studio}\nrules:  {os.path.join(studio, 'CHANNEL_RULES.md')}")


if __name__ == "__main__":
    main()
